export async function getAllRules(typeFilter) {
    const { db } = getFirebase();
    const constraints = [orderBy('order')];
    if (typeFilter) {
        const { where } = await import('firebase/firestore');
        constraints.unshift(where('type', '==', typeFilter));
    }
    const snapshot = await getDocs(query(collection(db, 'rules'), ...constraints));
    const rules = [];
    snapshot.forEach(d => rules.push({ id: d.id, ...d.data() }));
    return rules;
}

export async function getRule(id) {
    const { db } = getFirebase();
    const snap = await getDoc(doc(db, 'rules', id));
    if (!snap.exists()) return null;
    return { id: snap.id, ...snap.data() };
}

export async function createRule(data) {
    const { db } = getFirebase();
    const title = data.title.trim();
    const existing = await getAllRules();
    if (existing.some(r => (r.title || '').trim().toLowerCase() === title.toLowerCase())) {
        throw new Error('Правило с таким заголовком уже существует');
    }
    const ref = doc(collection(db, 'rules'));
    const payload = {
        type: data.type || 'general',
        title,
        content: data.content.trim(),
        order: data.order || 0,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString()
    };
    await setDoc(ref, payload);
    return { id: ref.id, ...payload };
}

export async function updateRule(id, data) {
    const { db } = getFirebase();
    const updates = {};
    if (data.title !== undefined) {
        const title = data.title.trim();
        const existing = await getAllRules();
        if (existing.some(r => r.id !== id && (r.title || '').trim().toLowerCase() === title.toLowerCase())) {
            throw new Error('Правило с таким заголовком уже существует');
        }
        updates.title = title;
    }
    if (data.content !== undefined) updates.content = data.content.trim();
    if (data.order !== undefined) updates.order = data.order;
    if (data.type !== undefined) updates.type = data.type;
    updates.updatedAt = new Date().toISOString();
    await setDoc(doc(db, 'rules', id), updates, { merge: true });
    return { id, ...updates };
}

export async function deleteRule(id) {
    const { db } = getFirebase();
    await deleteDoc(doc(db, 'rules', id));
}

export async function seedInitialRules() {
    const { db } = getFirebase();
    const snapshot = await getDocs(collection(db, 'rules'));

    // Не перезаписываем отредактированные статьи: добавляем только недостающие
    const existingTitles = new Set();
    snapshot.forEach(d => existingTitles.add(d.data().title));

    for (const data of SEED_RULES) {
        if (existingTitles.has(data.title)) continue;
        const ref = doc(collection(db, 'rules'));
        await setDoc(ref, {
            ...data,
            createdAt: new Date().toISOString(),
            updatedAt: new Date().toISOString()
        });
    }
}
